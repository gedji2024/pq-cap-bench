#!/usr/bin/env python3
"""Derive freshness.spthy from crisis.spthy by dropping the envelope-state premises of Device_Accept.

Soundness: removing premises from a rule (and the matching state conclusion) only adds traces, and every
other rule is unchanged. So each crisis trace is also a freshness trace with the same Accept/Send/RevealSess
actions; trace properties over those actions (P4, ctr_monotone) proved in freshness.spthy hold in
crisis.spthy. Tamarin needs this projection: with Hnd/!Env in Device_Accept the counter induction does not
terminate (formal/README.md).
"""
import pathlib
import sys

src = pathlib.Path(sys.argv[1]).read_text()
OLD = "DevCtr(D, %n), Hnd(D, <'hnd', h>), !Env(D, h, a, c), !DevKeys(D, pkPA, pkOP),"
NEW = "DevCtr(D, %n), !DevKeys(D, pkPA, pkOP),"
OLD_C = "[ DevCtr(D, %m), Hnd(D, <'hnd', h>) ]"
NEW_C = "[ DevCtr(D, %m) ]"
assert src.count(OLD) == 1 and src.count(OLD_C) == 1, "Device_Accept changed; update make_freshness.py"
# side conditions of the read-only premise-dropping lemma (formal/README.md): the dropped linear fact is consumed
# and re-produced identically; the other dropped premise is persistent
DROPPED_LINEAR, DROPPED_PERSISTENT = "Hnd(D, <'hnd', h>)", "!Env(D, h, a, c)"
assert DROPPED_LINEAR in OLD and DROPPED_LINEAR in OLD_C and DROPPED_PERSISTENT in OLD
assert OLD.replace(DROPPED_LINEAR + ", ", "").replace(DROPPED_PERSISTENT + ", ", "") == NEW
assert OLD_C.replace(", " + DROPPED_LINEAR, "") == NEW_C
out = src.replace(OLD, NEW).replace(OLD_C, NEW_C).replace("theory Crisis", "theory Freshness", 1)
out = "/* GENERATED by make_freshness.py from crisis.spthy -- do not edit. */\n" + out
# keep only the lemmas this projection is used for
head, lemmas = out.split("/* ---------------------------------------------------------------- executability */")
keep = []
for block in lemmas.split("\nlemma ")[1:]:
    name = block.split(":")[0].split()[0]
    if name in {"ctr_monotone", "P4_no_replay", "P4_injective_agreement"}:
        keep.append("lemma " + block.split("\n\n")[0].rstrip())
pathlib.Path(sys.argv[2]).write_text(head + "\n" + "\n\n".join(keep) + "\n\nend\n")
